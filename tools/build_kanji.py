#!/usr/bin/env python3
"""Build the kanji and vocabulary data files from open datasets.

Usage:  python3 -I tools/build_kanji.py <download dir> data/

The download dir must contain (see README → Data for where each comes from):
  kanjivg-main.zip      KanjiVG release, "main" variant        (CC BY-SA 3.0, Ulrich Apel)
  kanjidic2.xml.gz      KANJIDIC2 from EDRDG                     (CC BY-SA 4.0, EDRDG licence)
  JLPT_kanji_ALL.json   kanji → JLPT level, from Bluskyo/JLPT_Vocabulary (levels: Jonathan Waller, CC BY)
  vocab-n1.csv … vocab-n5.csv   from jamsinclair/open-anki-jlpt-decks src/n1..n5.csv (Waller, CC BY)

Writes:
  data/kanji.js           window.KANJI = { levels: {5: "日一…", …}, info: {"日": [level, strokes, freq, meanings, on, kun]} }
  data/vocab.js           window.VOCAB = { 5: [[word, reading, meaning], …], … }
  data/strokes-n5.js … data/strokes-n1.js   stroke paths per level, added to window.STROKES (loaded on demand)

Kanji within a level are ordered by newspaper frequency. Words within a level come in the order
their kanji are taught: kana-only words first, then words whose kanji are all early in the kanji order.
Re-run this regularly with fresh downloads (the EDRDG licence asks for regular updates).
"""
import csv, gzip, json, re, sys, zipfile, pathlib
import xml.etree.ElementTree as ET

src = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
LEVELS = [5, 4, 3, 2, 1]
dump = lambda v: json.dumps(v, ensure_ascii=False, separators=(',', ':'))

# ---------- kanji: levels + KANJIDIC2 ----------
jlpt = {k: int(v) for k, v in json.loads((src / 'JLPT_kanji_ALL.json').read_text('utf-8')).items()}

kd = {}
with gzip.open(src / 'kanjidic2.xml.gz') as f:
    for _, el in ET.iterparse(f):
        if el.tag != 'character':
            continue
        lit = el.findtext('literal')
        if lit in jlpt:
            misc = el.find('misc')
            rm = el.find('reading_meaning')
            meanings, on, kun = [], [], []
            if rm is not None:
                for g in rm.findall('rmgroup'):
                    meanings += [m.text for m in g.findall('meaning') if 'm_lang' not in m.attrib and m.text]
                    on += [r.text for r in g.findall('reading') if r.get('r_type') == 'ja_on']
                    kun += [r.text for r in g.findall('reading') if r.get('r_type') == 'ja_kun']
            # (SKIP codes and other query codes are deliberately not used: different licence.)
            freq = misc.findtext('freq')
            kd[lit] = {
                'strokes': int(misc.findtext('stroke_count') or 0),
                'freq': int(freq) if freq else 9999,
                'meanings': meanings[:4], 'on': on[:4], 'kun': kun[:5],
            }
        el.clear()

missing = [k for k in jlpt if k not in kd]
order = {lv: sorted((k for k in jlpt if jlpt[k] == lv and k in kd), key=lambda k: (kd[k]['freq'], kd[k]['strokes'], k))
         for lv in LEVELS}
rank = {}
for lv in LEVELS:
    for k in order[lv]:
        rank[k] = len(rank)
info = {k: [lv, kd[k]['strokes'], kd[k]['freq'], kd[k]['meanings'], kd[k]['on'], kd[k]['kun']]
        for lv in LEVELS for k in order[lv]}

HEADER_KANJI = (
    "// Kanji data generated by tools/build_kanji.py.\n"
    "// Meanings, readings, stroke counts, frequency: KANJIDIC2, property of the Electronic Dictionary Research\n"
    "// and Development Group (https://www.edrdg.org/), used under its licence (CC BY-SA 4.0):\n"
    "// https://www.edrdg.org/edrdg/licence.html\n"
    "// JLPT levels: Jonathan Waller's JLPT lists (CC BY), via github.com/Bluskyo/JLPT_Vocabulary (MIT).\n"
    "// Unofficial: the JLPT has not published kanji lists since 2010.\n")
(out / 'kanji.js').write_text(HEADER_KANJI + "window.KANJI = " + dump({
    'levels': {lv: ''.join(order[lv]) for lv in LEVELS}, 'info': info}) + ";\n", 'utf-8')

# ---------- stroke order (KanjiVG), one file per level ----------
pat = re.compile(r'<path id="kvg:[0-9a-f]+-s(\d+)"[^>]*\sd="([^"]+)"')
no_strokes = []
with zipfile.ZipFile(src / 'kanjivg-main.zip') as z:
    names = set(z.namelist())
    for lv in LEVELS:
        data = {}
        for k in order[lv]:
            name = f'kanji/{ord(k):05x}.svg'
            if name not in names:
                no_strokes.append(k)
                continue
            strokes = sorted((int(n), d) for n, d in pat.findall(z.read(name).decode('utf-8')))
            if strokes:
                data[k] = [d for _, d in strokes]
        (out / f'strokes-n{lv}.js').write_text(
            "// Stroke-order data for JLPT N%d kanji, generated from KanjiVG (https://kanjivg.tagaini.net)\n"
            "// Copyright (C) 2009-2026 Ulrich Apel. Licensed CC BY-SA 3.0.\n"
            "// Each entry: SVG path strings in stroke order, viewBox 0 0 109 109.\n" % lv +
            "Object.assign(window.STROKES || (window.STROKES = {}), " + dump(data) + ");\n", 'utf-8')

# ---------- vocabulary ----------
def first_alt(s):
    return s.split(';')[0]

def clean_text(s):
    s = re.sub(r'[（(][^)）]*[)）]', '', first_alt(s))  # drop "(notes)"
    return re.sub(r'\s+', '', s).replace('〜', '～')

def clean_meaning(s):
    s = re.sub(r'\s+', ' ', s).strip()
    if len(s) > 90:
        cut = max(s.rfind(',', 0, 90), s.rfind(';', 0, 90))
        s = s[:cut] if cut > 20 else s[:90]
    return s

KANA = re.compile(r'^[぀-ヿ～ー・]+$')
seen = {}
vocab = {lv: [] for lv in LEVELS}
skipped = 0
for lv in LEVELS:  # easiest level first, so a word listed twice keeps its easier level
    for r in csv.DictReader(open(src / f'vocab-n{lv}.csv', encoding='utf-8')):
        word, reading = clean_text(r['expression']), clean_text(r['reading'])
        if not reading and KANA.match(word):
            reading = word
        if not word or not reading or not KANA.match(reading) or len(word) > 20 or len(reading) > 24:
            skipped += 1
            continue
        key = (word, reading)
        if key in seen:
            continue
        seen[key] = lv
        vocab[lv].append([word, reading, clean_meaning(r['meaning'])])

def word_rank(w):
    ks = [c for c in w[0] if '一' <= c <= '鿿' or c == '々']
    return max((rank.get(c, 100000) for c in ks), default=-1)

for lv in LEVELS:
    vocab[lv].sort(key=word_rank)  # stable: keeps list order among equals

(out / 'vocab.js').write_text(
    "// JLPT vocabulary generated by tools/build_kanji.py from github.com/jamsinclair/open-anki-jlpt-decks (MIT),\n"
    "// based on Jonathan Waller's JLPT lists (CC BY). Unofficial: no official lists exist since 2010.\n"
    "window.VOCAB = " + dump(vocab) + ";\n", 'utf-8')

# ---------- report ----------
print('kanji:', {lv: len(order[lv]) for lv in LEVELS}, 'missing from KANJIDIC2:', missing)
print('no KanjiVG strokes:', no_strokes)
print('vocab:', {lv: len(vocab[lv]) for lv in LEVELS}, 'skipped:', skipped)
for f in ['kanji.js', 'vocab.js'] + [f'strokes-n{lv}.js' for lv in LEVELS]:
    print(f'  data/{f}: {(out / f).stat().st_size:,} bytes')
